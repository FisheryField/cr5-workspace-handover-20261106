for off in 0x0000 0x0100 0x0120 0x0130 0x0800 0x0808 0x0900 0x1000 0x1100 0x1200 0x1400 0x1480 0x1800 0x1900 0x1a00 0x1a30 0x1c00 0x1fff; do
  printf "off=%s  " $off
  /tmp/ecat_mbx peek eth0 0x3f0 $off 8 2>&1 | head -1
done
echo
echo "=== 用 512 字节读 0x1800 / 0x1a30（与控制器一致的长度）==="
/tmp/ecat_mbx peek eth0 0x3f0 0x1800 512 2>&1 | head -1
/tmp/ecat_mbx peek eth0 0x3f0 0x1a30 512 2>&1 | head -1
